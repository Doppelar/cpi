import { EasyNote } from "./explain-mode";

/* ───────── 消費者物価指数 ───────── */

export function CpiIntroNote({
  areaLabel,
  monthLabel,
  yoy,
  yen,
}: {
  areaLabel: string;
  monthLabel: string;
  yoy: string;
  yen: number | null;
}) {
  return (
    <EasyNote title="消費者物価指数ってなに？">
      <p>
        「物価」とは、お店で売っているものや、散髪・電車などのサービスの<strong>値段</strong>のことです。
        消費者物価指数は、ふだんの暮らしで買う<strong>約580種類</strong>のもの（お米、パン、卵、電気代、スマホ代、家賃など）の値段をまとめて、
        「全体として値段が上がったか、下がったか」を1つの数字にしたものです。
      </p>
      <p>
        {areaLabel}の{monthLabel}は<strong>{yoy}</strong>。これは「1年前の同じ月と比べて、買い物全体の値段が{yoy}変わった」という意味です。
        {yen != null && (
          <>
            1年前に<strong>10,000円</strong>で買えたものが、いまは<strong>約{yen.toLocaleString()}円</strong>かかる、と考えるとイメージしやすくなります。
          </>
        )}
      </p>
      <p>
        右の4つのカードは、計算から一部を除いた数字です。たとえば野菜や魚は、雨が多い・暑すぎるなど
        <strong>天気だけで値段が大きく変わる</strong>ので、それを除いた数字（コア）も見ます。
        電気・ガス・ガソリンは<strong>外国の石油の値段</strong>で大きく動くので、それも除いた数字（コアコア）を見ると、
        日本の中での「値上がりの本当の勢い」がわかります。
      </p>
    </EasyNote>
  );
}

export function CpiTrendNote() {
  return (
    <EasyNote title="このグラフの見方">
      <p>
        横は時間（左が昔、右が最近）、縦は「1年前と比べて何%値段が上がったか」です。
        線が<strong>上にあるほど値上がりが大きく</strong>、0より下なら1年前より<strong>値下がり</strong>しています。
      </p>
      <p>
        点線の<strong>2%</strong>は、日本銀行（国のお金を管理する銀行）が「このくらいの値上がりがちょうどいい」と目標にしている数字です。
        物価が少しずつ上がり、それ以上に給料も上がるのが、経済にとってよい状態と考えられています。
      </p>
      <p>グラフを指でなぞると、その月の数字が出ます。右上のボタンで、見る期間を変えられます。</p>
    </EasyNote>
  );
}

export function CpiContribNote() {
  return (
    <EasyNote title="「寄与度」は、値上がりの原因の内訳">
      <p>
        物価全体が2%上がったとしても、その原因は「食べ物が上がった」「電気代が上がった」などいろいろです。
        このグラフは、<strong>どの種類の値上がりが、全体を何%分押し上げたか</strong>を色分けして積み上げています。
      </p>
      <p>
        たとえば青い「食料」の棒が大きい月は、食べ物の値上がりが主な原因です。棒が0より下に出ている色は、
        その種類の値段が下がって、全体を<strong>押し下げた</strong>ことを表します。黒い線が、全部を合わせた物価の上がり方です。
      </p>
      <p>
        ポイント（pt）は、全体の上がり幅のうち、その種類が受け持った分の大きさです。全部の色を足すと、黒い線の数字になります。
      </p>
    </EasyNote>
  );
}

export function CpiMonthNote() {
  return (
    <EasyNote title="月を選んで、何の値段が動いたかを調べよう">
      <p>
        上の「年月」を選ぶと、その月に<strong>値段が大きく上がったもの・下がったもの</strong>がランキングで出ます。
        気になる品目を押すと、その値段の動きがグラフで見られます。
      </p>
      <ul className="list-disc space-y-1 pl-5">
        <li>
          <strong>前年同月比</strong>：1年前の同じ月と比べて、値段が何%変わったか。
        </li>
        <li>
          <strong>前月比</strong>：先月と比べて、値段が何%変わったか。夏はエアコン、年末は旅行など、季節の影響も入ります。
        </li>
        <li>
          <strong>寄与度</strong>：物価全体への影響の大きさ。値上がり率が大きくても、みんながあまり買わないものなら小さくなります。
        </li>
        <li>
          <strong>ウエイト</strong>：家計が1万円使うとき、そのものに何円使っているか。大きいほど、物価全体に強く効きます。
        </li>
      </ul>
    </EasyNote>
  );
}

export function CpiWatchNote() {
  return (
    <EasyNote title="身近なものの値段の動き">
      <p>
        お米や卵、電気代など、暮らしに身近なものの「1年前と比べた値段の変化」を並べています。
        大きな数字が<strong>いまの値上がり率</strong>、下の小さな線が<strong>3年間の動き</strong>です。
        線が横の線（0%）より上なら、1年前より高くなっています。
      </p>
    </EasyNote>
  );
}

/* ───────── 景気動向指数 ───────── */

const JUDGMENT_EASY: Record<string, string> = {
  改善: "景気がよくなっている、という意味です。",
  足踏み: "よくなっていた景気が、いったん立ち止まっている、という意味です。",
  上方への局面変化:
    "悪かった景気が、少し前から上向きに変わったかもしれない、という意味です。",
  下方への局面変化:
    "よかった景気が、少し前から下向きに変わったかもしれない、という意味です。",
  悪化: "景気が悪くなっている、という意味です。",
  下げ止まり: "悪くなっていた景気の下がり方が止まってきた、という意味です。",
};

export function KeikiIntroNote({ label }: { label: string | null }) {
  return (
    <EasyNote title="景気動向指数ってなに？">
      <p>
        「景気」とは、世の中のお金の回りぐあいのことです。ものがよく売れて、会社がもうかり、働く人や給料が増えると
        「<strong>景気がいい</strong>」と言います。反対に、ものが売れず、仕事が減ると「景気が悪い」と言います。
      </p>
      <p>
        景気動向指数は、工場でつくられた量、お店の売り上げ、仕事を探している人に対する求人の数など、
        <strong>約30の数字</strong>をまとめて、景気がよくなっているか悪くなっているかを表したものです。国（内閣府）が毎月発表しています。
      </p>
      {label && (
        <p>
          いまの国の判断は「<strong>{label}</strong>」。{JUDGMENT_EASY[label] ?? ""}
        </p>
      )}
      <p>
        「一致指数」が<strong>いまの景気</strong>、「先行指数」が<strong>少し先の景気</strong>、「遅行指数」が
        <strong>あとから景気を確かめる数字</strong>です。天気にたとえると、先行指数は「空の雲の動き」、一致指数は「いまの天気」、
        遅行指数は「雨のあとの地面のぬれ具合」のようなものです。
      </p>
    </EasyNote>
  );
}

